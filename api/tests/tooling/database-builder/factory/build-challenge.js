import { databaseBuffer } from '../database-buffer.js';

export function buildChallenge({
  id,
  type,
  t1Status,
  t2Status,
  t3Status,
  status,
  skillId,
  embedHeight,
  timer,
  format,
  autoReply,
  locales,
  focusable,
  genealogy,
  pedagogy,
  author,
  declinable,
  version,
  alternativeVersion,
  accessibility1,
  accessibility2,
  spoil,
  responsive,
  shuffled,
  createdAt,
  updatedAt,
  validatedAt,
  archivedAt,
  madeObsoleteAt,
  isQualityOk,
  assessmentMaintenanceTags,
  translationMaintenanceTags,
} = {}) {
  return databaseBuffer.pushInsertable({
    tableName: 'challenges',
    values: {
      id,
      type,
      t1Status,
      t2Status,
      t3Status,
      status,
      skillId,
      embedHeight,
      timer,
      format,
      autoReply,
      locales,
      focusable,
      genealogy,
      pedagogy,
      author,
      declinable,
      version,
      alternativeVersion,
      accessibility1,
      accessibility2,
      spoil,
      responsive,
      shuffled,
      createdAt,
      updatedAt,
      validatedAt,
      archivedAt,
      madeObsoleteAt,
      isQualityOk,
      assessmentMaintenanceTags,
      translationMaintenanceTags,
    },
  });
}
