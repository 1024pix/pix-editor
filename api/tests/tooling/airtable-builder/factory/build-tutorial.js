export function buildTutorial({
  id,
  airtableId = id,
  title,
  format,
  duration,
  source,
  link,
  locale,
  language,
  license,
  level,
  crush,
  tagAirtableIds,
  tutorialForSkills,
  furtherInformation,
} = {}) {
  return {
    id: airtableId,
    'fields': {
      'id persistant': id,
      'Titre': title,
      'Format': format,
      'Durée': duration,
      'Source': source,
      'Lien': link,
      'Langue': locale ?? language,
      'License': license,
      'niveau': level,
      'CoupDeCoeur': crush,
      'Tags': tagAirtableIds ?? [],
      'Solution à': tutorialForSkills,
      'En savoir plus': furtherInformation,
    },
  };
}
